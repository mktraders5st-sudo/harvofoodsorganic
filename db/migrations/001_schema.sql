-- Harvo Foods Organic: PostgreSQL (Supabase) schema.
-- Safe to run more than once: it only creates what doesn't exist yet. No data is dropped or changed.

-- ── Catalogue ────────────────────────────────────────────

create table if not exists categories (
  id          text primary key check (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name        text not null check (length(name) between 2 and 60),
  sort_order  integer not null default 0
);

create table if not exists products (
  id           text primary key check (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(id) <= 60),
  category_id  text not null references categories(id),
  name         text not null check (length(name) between 2 and 80),
  description  text not null default '' check (length(description) <= 500),
  color        text not null default '#3f9d4c' check (color ~ '^#[0-9a-fA-F]{6}$'),
  rim          text check (rim ~ '^#[0-9a-fA-F]{6}$'),
  rating       integer not null default 5 check (rating between 0 and 5),
  reviews      integer not null default 0 check (reviews >= 0),
  badge        text check (badge in ('Best Seller', 'New')),
  featured     boolean not null default false,
  active       boolean not null default true,
  sort_order   integer not null default 0,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists products_category_idx on products (category_id);

-- Product photos. The one with the lowest sort_order is the main photo.
create table if not exists product_images (
  id          integer generated by default as identity primary key,
  product_id  text not null references products(id) on delete cascade,
  url         text not null check (length(url) <= 300 and (url ~ '^/images/[A-Za-z0-9_./-]+$' or url ~ '^https://')),
  alt         text not null default '' check (length(alt) <= 150),
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  unique (product_id, sort_order)
);

-- Package sizes (e.g. 50 g, 100 g, 250 g), each with its own price (PKR) and stock.
create table if not exists product_variants (
  id          integer generated by default as identity primary key,
  product_id  text not null references products(id) on delete cascade,
  grams       integer not null check (grams between 1 and 100000),
  price       integer not null check (price between 0 and 10000000),
  stock       integer not null default 0 check (stock between 0 and 1000000),
  active      boolean not null default true,
  unique (product_id, grams)
);
create index if not exists product_variants_product_idx on product_variants (product_id);

-- ── Orders (cash on delivery only; no payment details are ever stored) ──

create table if not exists orders (
  id               integer generated by default as identity primary key,
  order_number     text not null unique,
  idempotency_key  text not null unique,
  status           text not null default 'pending'
                   check (status in ('pending', 'confirmed', 'dispatched', 'delivered', 'cancelled')),
  customer_name    text not null check (length(customer_name) between 2 and 60),
  phone            text not null check (phone ~ '^03[0-9]{9}$'),
  email            text check (length(email) <= 100),
  city             text not null check (length(city) between 2 and 40),
  address          text not null check (length(address) between 10 and 300),
  notes            text check (length(notes) <= 300),
  payment_method   text not null default 'COD' check (payment_method = 'COD'),
  subtotal         integer not null check (subtotal >= 0),
  delivery_fee     integer not null check (delivery_fee >= 0),
  total            integer not null check (total >= 0),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists orders_created_idx on orders (created_at desc);
create index if not exists orders_status_idx on orders (status);
create index if not exists orders_phone_idx on orders (phone);

-- Items keep a copy of the name and price, so later catalogue edits never change past orders.
create table if not exists order_items (
  id            integer generated by default as identity primary key,
  order_id      integer not null references orders(id) on delete cascade,
  product_id    text not null,
  product_name  text not null,
  grams         integer not null check (grams > 0),
  unit_price    integer not null check (unit_price >= 0),
  qty           integer not null check (qty between 1 and 99),
  line_total    integer not null check (line_total >= 0)
);
create index if not exists order_items_order_idx on order_items (order_id);

-- Who changed an order's status, and when.
create table if not exists order_status_history (
  id           integer generated by default as identity primary key,
  order_id     integer not null references orders(id) on delete cascade,
  from_status  text,
  to_status    text not null,
  changed_by   text not null,
  changed_at   timestamptz not null default now()
);
create index if not exists order_status_history_order_idx on order_status_history (order_id);

-- ── Sign-in / checkout attempt limits (shared by all server instances) ──

create table if not exists rate_limits (
  key       text primary key,
  count     integer not null,
  reset_at  timestamptz not null
);
